#!/usr/bin/env python3
"""
qgl_cqc.py -- from the E8 -> H4 projection (qgl_e8) to the compound of five cuboctahedra (3D) and the 20G.

Pipeline, following the description in Fang & Irwin (arXiv:1511.07786) as far as I could read it:

  1. shell600()          the 120 outer-shell vectors of the projected E8 roots, normalised: a 600-cell.
  2. h4_rotations()      the 7200 proper symmetries of that 600-cell, generated from reflections in its vertices.
  3. inscribed_24cells() the 25 24-cells inscribed in the 600-cell (found as 24-cliques of the inner-product graph with
                         inner products in {0, +-1/2, +-1}); five disjoint ones form a partition of the 120 vertices.
  4. equators()          the cuboctahedral equators of a 24-cell: central hyperplanes containing exactly 12 of its vertices.
  5. c5c_from_4d()       isoclinic symmetries of the 600-cell that carry one equator hyperplane of each of the other four
                         24-cells onto a fixed hyperplane of the first.  Each chirality is explored separately.

Checked in tests/test_cqc.py: 120 shell vectors with the 600-cell neighbour structure, group order 7200, 25 inscribed
24-cells and a five-fold partition, 12 cuboctahedral equators per 24-cell, and whether the 4D construction can produce
a compound of five cuboctahedra isometric to the one built directly from the icosahedral axes in qgl_qsn.

Not claimed: which chirality is "left" or "right" (that depends on an orientation convention I did not fix; they are
labelled +1 and -1 by the sign of the Pfaffian of the antisymmetric part), and no claim about the full infinite
Elser-Sloane quasicrystal.  I use the 600-cell shell only.
"""
from __future__ import annotations

import functools
import itertools
from typing import Dict, FrozenSet, List, Set, Tuple

import numpy as np

import qgl_e8 as e8
import qgl_qsn as qsn

_R = 7


def _key(x: np.ndarray) -> Tuple[float, ...]:
    return tuple(np.round(np.asarray(x).ravel(), _R) + 0.0)


def shell600() -> np.ndarray:
    """120 unit vectors in R^4: the outer shell of the projected E8 roots."""
    roots = e8.e8_roots()
    p_phys, _ = e8.h4_projection()
    x = roots @ p_phys.T
    rad = np.linalg.norm(x, axis=1)
    shell = x[np.isclose(rad, rad.max(), atol=1e-7)]
    return shell / np.linalg.norm(shell, axis=1, keepdims=True)


def reflection4(v: np.ndarray) -> np.ndarray:
    return np.eye(4) - 2.0 * np.outer(v, v) / float(v @ v)


def h4_group(v: np.ndarray, max_order: int = 14400) -> List[np.ndarray]:
    """Group generated by the reflections in 8 vertices of the 600-cell (all of H4 when it reaches 14400)."""
    gens = [reflection4(v[i]) for i in range(0, len(v), 15)]
    seen = {_key(np.eye(4)): np.eye(4)}
    frontier = [np.eye(4)]
    while frontier:
        nxt = []
        for m in frontier:
            for g in gens:
                p = g @ m
                k = _key(p)
                if k not in seen:
                    seen[k] = p
                    nxt.append(p)
                    if len(seen) > max_order:
                        raise RuntimeError("group larger than H4")
        frontier = nxt
    return list(seen.values())


def h4_rotations(v: np.ndarray) -> List[np.ndarray]:
    return [m for m in h4_group(v) if np.linalg.det(m) > 0]


def _bron_kerbosch(r: Set[int], p: Set[int], x: Set[int], adj: Dict[int, Set[int]], out: List[FrozenSet[int]]):
    if not p and not x:
        out.append(frozenset(r))
        return
    pivot = max(p | x, key=lambda u: len(adj[u] & p))
    for u in list(p - adj[pivot]):
        _bron_kerbosch(r | {u}, p & adj[u], x & adj[u], adj, out)
        p = p - {u}
        x = x | {u}


def inscribed_24cells(v: np.ndarray) -> List[FrozenSet[int]]:
    """All 24-cells inscribed in the 600-cell, as frozensets of vertex indices (there are 25)."""
    gram = v @ v.T
    ok = np.zeros_like(gram, dtype=bool)
    for val in (0.0, 0.5, -0.5, -1.0):
        ok |= np.isclose(gram, val, atol=1e-7)
    found: Set[FrozenSet[int]] = set()
    for v0 in range(len(v)):
        nb = {u for u in range(len(v)) if u != v0 and ok[v0, u]}
        adj = {u: {w for w in nb if w != u and ok[u, w]} for u in nb}
        cl: List[FrozenSet[int]] = []
        _bron_kerbosch(set(), set(nb), set(), adj, cl)
        for c in cl:
            if len(c) == 23:
                found.add(frozenset(c | {v0}))
        if len(found) >= 25 and v0 > 20:
            break
    return sorted(found, key=lambda s: sorted(s))


def partition_into_five(cells: List[FrozenSet[int]]) -> List[FrozenSet[int]]:
    def rec(sel, taken):
        if len(sel) == 5:
            return sel
        for c in cells:
            if not (c & taken) and (not sel or sorted(c)[0] > sorted(sel[-1])[0]):
                got = rec(sel + [c], taken | c)
                if got:
                    return got
        return None
    out = rec([], frozenset())
    assert out is not None
    return out


def all_partitions_into_five(cells: List[FrozenSet[int]]) -> List[List[FrozenSet[int]]]:
    """Every partition of the 120 vertices into five disjoint inscribed 24-cells."""
    res: List[List[FrozenSet[int]]] = []

    def rec(sel, taken):
        if len(sel) == 5:
            res.append(sel)
            return
        for c in cells:
            if not (c & taken) and (not sel or sorted(c)[0] > sorted(sel[-1])[0]):
                rec(sel + [c], taken | c)
    rec([], frozenset())
    return res


def equators(pts: np.ndarray) -> List[Tuple[np.ndarray, List[int]]]:
    """Central hyperplanes meeting the 24 points in exactly 12 (cuboctahedra): (unit normal, indices)."""
    found: Dict[Tuple[float, ...], Tuple[np.ndarray, List[int]]] = {}
    for tri in itertools.combinations(range(len(pts)), 3):
        a = pts[list(tri)]
        _, s, vt = np.linalg.svd(a)
        if s[2] < 1e-7:
            continue
        n = vt[3]
        on = [i for i in range(len(pts)) if abs(pts[i] @ n) < 1e-7]
        if len(on) == 12:
            first = next(c for c in n if abs(c) > 1e-9)
            n = n * np.sign(first)
            found[_key(n)] = (n, on)
    return list(found.values())


def chirality(r: np.ndarray) -> int:
    """+1 / -1 for an isoclinic rotation (sign of the Pfaffian of the antisymmetric part), 0 otherwise."""
    a = 0.5 * (r - r.T)
    pf = a[0, 1] * a[2, 3] - a[0, 2] * a[1, 3] + a[0, 3] * a[1, 2]
    s = np.linalg.svd(a, compute_uv=False)
    if s[0] < 1e-7 or abs(s[0] - s[2]) > 1e-7:
        return 0
    return int(np.sign(pf))


def _basis_perp(w: np.ndarray) -> np.ndarray:
    _, _, vt = np.linalg.svd(w.reshape(1, 4))
    return vt[1:]                                  # 3 x 4, orthonormal rows orthogonal to w


def qmul(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Quaternion product in coordinates (w, x, y, z)."""
    aw, ax, ay, az = a
    bw, bx, by, bz = b
    return np.array([aw * bw - ax * bx - ay * by - az * bz,
                     aw * bx + ax * bw + ay * bz - az * by,
                     aw * by - ax * bz + ay * bw + az * bx,
                     aw * bz + ax * by - ay * bx + az * bw])


def qconj(a: np.ndarray) -> np.ndarray:
    return a * np.array([1.0, -1.0, -1.0, -1.0])


def left_matrix(q: np.ndarray) -> np.ndarray:
    """Matrix of x -> q x (a left-isoclinic rotation for unit q)."""
    return np.array([qmul(q, e) for e in np.eye(4)]).T


def right_matrix(q: np.ndarray) -> np.ndarray:
    """Matrix of x -> x q (a right-isoclinic rotation for unit q)."""
    return np.array([qmul(e, q) for e in np.eye(4)]).T


def isoclinic_taking(a: np.ndarray, b: np.ndarray, side: str) -> np.ndarray:
    """The unique isoclinic rotation of the given side ('left' or 'right') with R a = b (a, b unit vectors)."""
    if side == "left":
        return left_matrix(qmul(b, qconj(a)))
    return right_matrix(qmul(qconj(a), b))


def side_chirality(side: str) -> int:
    """Chirality label (sign of the Pfaffian, as in chirality()) of left or right multiplication."""
    q = np.array([np.cos(0.3), np.sin(0.3), 0.0, 0.0])
    return chirality(left_matrix(q) if side == "left" else right_matrix(q))


@functools.lru_cache(maxsize=1)
def _setup():
    """Shell, its 7200 rotations and the ten partitions into five 24-cells (computed once)."""
    v = shell600()
    return v, h4_rotations(v), all_partitions_into_five(inscribed_24cells(v))


def five_fold_isoclinic(v: np.ndarray, cells: List[FrozenSet[int]], chir: int, rots=None):
    """An isoclinic symmetry g of the 600-cell with g^5 = 1 that cycles the five 24-cells of `cells`.
    Returns (g, ordered list of the five cells D_0, g D_0, ..., g^4 D_0) or None."""
    lookup = {_key(p): i for i, p in enumerate(v)}
    cellset = {c: n for n, c in enumerate(cells)}
    for r in (rots if rots is not None else h4_rotations(v)):
        if chirality(r) != chir or np.allclose(r, np.eye(4)):
            continue
        if not np.allclose(np.linalg.matrix_power(r, 5), np.eye(4), atol=1e-8):
            continue
        order = [0]
        cur = cells[0]
        ok = True
        for _ in range(4):
            img = frozenset(lookup[_key(r @ v[i])] for i in cur)
            if img not in cellset:
                ok = False
                break
            cur = img
            order.append(cellset[img])
        if ok and len(set(order)) == 5:
            return r, [cells[n] for n in order]
    return None


def c5c_from_4d(g_chirality: int = 1, use_side: str = "same"):
    """Rotate the cuboctahedral equators of the five 24-cells into one hyperplane.

    D_k = g^k D_0 for a five-fold isoclinic symmetry g of chirality `g_chirality`; the equator of D_k is g^k of one fixed
    equator of D_0.  Each is carried onto the fixed hyperplane of D_0 by the unique isoclinic rotation of the chosen
    side: use_side='same' (same chirality as g) or 'opposite'.  Returns (points_3d (5, 12, 3), n_distinct_vertices)."""
    v, rots, parts = _setup()
    found = None
    for part in parts:
        found = five_fold_isoclinic(v, part, g_chirality, rots)
        if found is not None:
            break
    if found is None:
        raise RuntimeError("no five-fold isoclinic symmetry found")
    g, order = found
    d0 = v[sorted(order[0])]
    w0, on0 = equators(d0)[0]
    basis = _basis_perp(w0)
    c0 = d0[on0]
    same = "left" if side_chirality("left") == g_chirality else "right"
    side = same if use_side == "same" else ("right" if same == "left" else "left")
    out = []
    gk = np.eye(4)
    for k in range(5):
        wk = gk @ w0
        ck = c0 @ gk.T
        m = isoclinic_taking(wk, w0, side)
        out.append((ck @ m.T) @ basis.T)
        gk = g @ gk
    pts = np.array(out)
    distinct = len({_key(p) for p in pts.reshape(-1, 3)})
    return pts, distinct


def distance_signature(pts: np.ndarray) -> np.ndarray:
    d = np.linalg.norm(pts[:, None] - pts[None, :], axis=2)
    return np.sort(d[np.triu_indices(len(pts), 1)])


def reference_c5c() -> np.ndarray:
    """The 60 cuboctahedron vertices of the 20G built directly from the icosahedral axes (qgl_qsn)."""
    return qsn.cluster_20g()[1:]
